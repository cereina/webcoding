import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {registerHooks} from 'node:module';
import {JSDOM} from 'jsdom';
registerHooks({load(url,context,next){if(url.endsWith('.css'))return {format:'module',source:'',shortCircuit:true};return next(url,context);}});
const {setupBulkTables}=await import('../bulk-tables.ts');
test('bulk window reviews captions, cancels safely and commits links and classes',()=>{
 const dom=new JSDOM(readFileSync(new URL('../index.html',import.meta.url),'utf8'));
 globalThis.document=dom.window.document;
 dom.window.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
 dom.window.HTMLDialogElement.prototype.close=function(){this.open=false;};
 const original='<p>Annual results</p><table><tr><td>1</td></tr></table>';let source=original;
 setupBulkTables({getSource:()=>source,commit:html=>source=html});
 const open=document.getElementById('edit-tables').nextElementSibling;
 const dialog=document.querySelector('.bulk-tables-dialog');
 const click=selector=>dialog.querySelector(selector).click();
 open.click();assert.equal(dialog.querySelector('#bulk-caption-0').value,'');
 click('[data-accept-caption="0"]');assert.equal(dialog.querySelector('#bulk-caption-0').value,'Annual results');
 click('[data-accept-caption="0"]');assert.equal(dialog.querySelector('#bulk-caption-0').value,'');
 click('[data-action=ids]');assert.equal(source,original);
 click('[data-action=cancel]');assert.equal(source,original);
 open.click();dialog.querySelector('#bulk-toc-title').value='Tables';
 click('[data-accept-caption="0"]');click('[data-class=table-bordered]');click('[data-action=apply]');
 assert.equal(dialog.open,false);
 const doc=new JSDOM(source).window.document;
 assert.equal(doc.querySelector('caption').textContent,'Annual results');assert.equal(doc.querySelector('p'),null);
 assert.ok(doc.querySelector('table.table.table-bordered[id]'));assert.equal(doc.querySelector('nav a').textContent,'Annual results');
 open.click();source+='<!-- External edit -->';click('[data-action=apply]');
 assert.equal(dialog.open,true);assert.match(dialog.querySelector('[role=status]').textContent,/document changed/);
});
