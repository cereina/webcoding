import { promises as fs } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const lockPath = path.join(root, 'package-lock.json');
const nodeModules = path.join(root, 'node_modules');
const outputPath = path.join(root, 'public', 'THIRD_PARTY_LICENSES.txt');

const lock = JSON.parse(await fs.readFile(lockPath, 'utf8'));
const packageEntries = Object.keys(lock.packages ?? {})
  .filter(key => key.startsWith('node_modules/'))
  .sort((a, b) => a.localeCompare(b));

const licenseFilePattern = /^(?:licen[cs]e|copying|notice)(?:\..+)?$/i;
const packages = new Map();

function repositoryText(repository) {
  if (!repository) return '';
  if (typeof repository === 'string') return repository;
  if (typeof repository.url === 'string') return repository.url;
  return '';
}

function licenseExpression(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (Array.isArray(pkg.licenses)) {
    return pkg.licenses
      .map(item => typeof item === 'string' ? item : item?.type)
      .filter(Boolean)
      .join(' OR ');
  }
  return 'Not declared in package.json';
}

for (const packageKey of packageEntries) {
  const packageDir = path.join(root, packageKey);
  const packageJsonPath = path.join(packageDir, 'package.json');

  let pkg;
  try {
    pkg = JSON.parse(await fs.readFile(packageJsonPath, 'utf8'));
  } catch {
    continue;
  }

  const name = pkg.name || packageKey.replace(/^node_modules\//, '');
  const version = pkg.version || lock.packages?.[packageKey]?.version || 'unknown';
  const dedupeKey = `${name}@${version}`;
  if (packages.has(dedupeKey)) continue;

  let filenames = [];
  try {
    filenames = await fs.readdir(packageDir);
  } catch {
    filenames = [];
  }

  const licenseFiles = filenames
    .filter(filename => licenseFilePattern.test(filename))
    .sort((a, b) => a.localeCompare(b));

  const texts = [];
  for (const filename of licenseFiles) {
    try {
      const value = await fs.readFile(path.join(packageDir, filename), 'utf8');
      if (value.trim()) texts.push({ filename, value: value.trim() });
    } catch {
      // Ignore unreadable optional notice files; metadata is still recorded.
    }
  }

  packages.set(dedupeKey, {
    name,
    version,
    license: licenseExpression(pkg),
    homepage: typeof pkg.homepage === 'string' ? pkg.homepage : '',
    repository: repositoryText(pkg.repository),
    texts,
  });
}

const sorted = [...packages.values()].sort((a, b) =>
  a.name.localeCompare(b.name) || a.version.localeCompare(b.version)
);

const lines = [
  'MAPLE DOCUMENT STUDIO - THIRD-PARTY LICENSES',
  '============================================================',
  '',
  'Generated from the exact packages installed in node_modules.',
  'Do not edit this file manually; run: npm run licenses',
  '',
  `Packages documented: ${sorted.length}`,
  '',
];

for (const pkg of sorted) {
  lines.push('============================================================');
  lines.push(`${pkg.name}@${pkg.version}`);
  lines.push(`Declared license: ${pkg.license}`);
  if (pkg.homepage) lines.push(`Homepage: ${pkg.homepage}`);
  if (pkg.repository) lines.push(`Repository: ${pkg.repository}`);
  lines.push('');

  if (!pkg.texts.length) {
    lines.push('No standalone LICENSE / LICENCE / COPYING / NOTICE text file was packaged with this installed module.');
    lines.push('Refer to the declared license expression and upstream project for the applicable terms.');
    lines.push('');
    continue;
  }

  for (const notice of pkg.texts) {
    lines.push(`--- ${notice.filename} ---`);
    lines.push(notice.value);
    lines.push('');
  }
}

await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(outputPath, lines.join('\n').replace(/\n{4,}/g, '\n\n\n') + '\n', 'utf8');

const missing = sorted.filter(pkg => pkg.license === 'Not declared in package.json' && !pkg.texts.length);
console.log(`Generated ${path.relative(root, outputPath)} for ${sorted.length} packages.`);
if (missing.length) {
  console.warn(`Warning: ${missing.length} package(s) had neither declared license metadata nor packaged license text:`);
  for (const pkg of missing) console.warn(` - ${pkg.name}@${pkg.version}`);
}
